class MultilingualSchemeService:
    """
    Core multilingual resolution and caching service for schemes, benefits,
    eligibility requirements, and application guidance.
    """

    def __init__(self, bhashini_adapter: Optional[BhashiniAdapter] = None):
        self.adapter = bhashini_adapter or BhashiniAdapter()

    @staticmethod
    def compute_content_hash(text: str, source_lang: str, target_lang: str) -> str:
        """Compute SHA-256 hash for idempotent translation caching."""
        payload = f"{source_lang.lower().strip()}:{target_lang.lower().strip()}:{text.strip()}"
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()

    async def get_or_translate_text(
        self,
        db: Session,
        text: str,
        target_lang: str,
        source_lang: str = "en",
        scheme_slug: Optional[str] = None,
        field_type: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Translates text with multi-layer priority:
        1. Curated official multilingual dataset (reviewed)
        2. Persistent TranslationCache table in database
        3. Configured external translation provider (Bhashini) with timeout safety
        4. Verified phrase dataset / safe fallback preservation
        """
        if not text or not text.strip():
            return {"translated_text": "", "status": "empty", "is_reviewed": True, "provider_used": "noop"}

        target_lang = target_lang.lower().strip()
        source_lang = source_lang.lower().strip()

        # If already in target language, return as is
        if target_lang == source_lang:
            return {"translated_text": text, "status": "source", "is_reviewed": True, "provider_used": "source"}

        # 1. Check curated flagship benefits dataset
        if scheme_slug and field_type:
            dataset_scheme = MULTILINGUAL_SCHEME_BENEFITS.get(scheme_slug)
            if dataset_scheme:
                field_dict = dataset_scheme.get(field_type)
                if field_dict and target_lang in field_dict:
                    return {
                        "translated_text": field_dict[target_lang],
                        "status": "reviewed",
                        "is_reviewed": True,
                        "provider_used": "curated_official_dataset",
                    }

        content_hash = self.compute_content_hash(text, source_lang, target_lang)

        # 2. Check persistent TranslationCache table
        try:
            cached = db.execute(
                select(TranslationCache).where(
                    TranslationCache.content_hash == content_hash,
                    TranslationCache.target_language == target_lang,
                )
            ).scalar_one_or_none()

            if cached:
                return {
                    "translated_text": cached.translated_text,
                    "status": "reviewed" if cached.is_reviewed else "machine_translated",
                    "is_reviewed": cached.is_reviewed,
                    "provider_used": cached.provider_used,
                }
        except Exception:
            pass

        # 3. Check external translation provider (Bhashini) if configured
        if self.adapter.is_configured:
            try:
                external_translation = await self.adapter.translate_text(
                    text=text,
                    source_lang=source_lang,
                    target_lang=target_lang,
                )
                if external_translation and external_translation.strip():
                    try:
                        new_cache = TranslationCache(
                            content_hash=content_hash,
                            source_language=source_lang,
                            target_language=target_lang,
                            source_text=text,
                            translated_text=external_translation.strip(),
                            provider_used="bhashini",
                            is_reviewed=False,
                        )
                        db.add(new_cache)
                        db.commit()
                    except Exception:
                        db.rollback()

                    return {
                        "translated_text": external_translation.strip(),
                        "status": "machine_translated",
                        "is_reviewed": False,
                        "provider_used": "bhashini",
                    }
            except Exception as exc:
                logger.warning("Bhashini translation failed: %s", exc)

        # 4. Fallback: preserve original text safely while marking source status
        return {
            "translated_text": text,
            "status": "source_preserved",
            "is_reviewed": True,
            "provider_used": "official_source_preservation",
        }

    async def get_localized_scheme_benefits(
        self,
        db: Session,
        scheme: GovernmentScheme,
        target_lang: str,
    ) -> Dict[str, Any]:
        """
        Produce fully localized benefit details for a scheme in the requested language.
        Preserves verified financial amounts, percentages, and official source citations.
        """
        raw_b = scheme.benefit_details or {}
        target_lang = (target_lang or "en").lower().strip()

        is_verified = raw_b.get("is_verified", scheme.verification_status == "verified")
        assistance_type_en = raw_b.get("assistance_type") or "Welfare Assistance & Citizen Support"
        benefit_amount_en = raw_b.get("benefit_amount")
        frequency_en = raw_b.get("frequency_or_duration")
        benefits_provided_en = raw_b.get("benefits_provided") or scheme.description
        conditions_en = raw_b.get("conditions_limitations") or "Subject to verified citizen eligibility rules and valid application submission."

        # Check curated dataset first for flagship schemes (pm-svanidhi, pm-kisan, ayushman, etc.)
        curated = MULTILINGUAL_SCHEME_BENEFITS.get(scheme.slug)

        if curated:
            trans_assist = curated.get("assistance_type", {}).get(target_lang) or curated.get("assistance_type", {}).get("hi") or assistance_type_en
            trans_freq = curated.get("frequency_or_duration", {}).get(target_lang) or curated.get("frequency_or_duration", {}).get("hi") or frequency_en
            trans_benefits = curated.get("benefits_provided", {}).get(target_lang) or curated.get("benefits_provided", {}).get("hi") or benefits_provided_en
            trans_cond = curated.get("conditions_limitations", {}).get(target_lang) or curated.get("conditions_limitations", {}).get("hi") or conditions_en
            status = "reviewed"
            provider = "curated_official_dataset"
        else:
            # Dynamic translation pipeline with caching
            assist_res = await self.get_or_translate_text(db, assistance_type_en, target_lang, scheme_slug=scheme.slug, field_type="assistance_type")
            freq_res = await self.get_or_translate_text(db, frequency_en or "", target_lang, scheme_slug=scheme.slug, field_type="frequency_or_duration") if frequency_en else {"translated_text": None}
            benefits_res = await self.get_or_translate_text(db, benefits_provided_en, target_lang, scheme_slug=scheme.slug, field_type="benefits_provided")
            cond_res = await self.get_or_translate_text(db, conditions_en, target_lang, scheme_slug=scheme.slug, field_type="conditions_limitations")

            trans_assist = assist_res["translated_text"] or assistance_type_en
            trans_freq = freq_res["translated_text"] or frequency_en
            trans_benefits = benefits_res["translated_text"] or benefits_provided_en
            trans_cond = cond_res["translated_text"] or conditions_en
            status = assist_res.get("status", "reviewed")
            provider = assist_res.get("provider_used", "database_store")

        official_url = raw_b.get("official_source_url") or scheme.official_source_url or scheme.official_application_url

        return {
            "scheme_id": scheme.id,
            "scheme_slug": scheme.slug,
            "display_name": scheme.display_name,
            "target_language": target_lang,
            "is_verified": is_verified,
            "assistance_type": trans_assist,
            "benefit_amount": benefit_amount_en,  # Preserved exact currency & figures
            "frequency_or_duration": trans_freq,
            "benefits_provided": trans_benefits,
            "conditions_limitations": trans_cond,
            "intended_beneficiaries": raw_b.get("intended_beneficiaries") or scheme.beneficiary_groups or [],
            "official_source_url": official_url,
            "last_verified_at": raw_b.get("last_verified_at") or (scheme.last_verified_at.isoformat() if scheme.last_verified_at else None),
            "translation_status": status,
            "is_reviewed": True if curated else (status == "reviewed"),
            "provider_used": provider,
            "supported_languages": list(SCHEDULED_LANGUAGES_22) + ["en"],
        }


# Singleton instance
multilingual_scheme_service = MultilingualSchemeService()
